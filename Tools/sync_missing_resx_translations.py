def escape_xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def parse_keys(path: str) -> set[str]:
    tree = ET.parse(path)
    return {
        data.get("name")
        for data in tree.getroot().findall("data")
        if data.get("name") and data.find("value") is not None
    }


def format_entry(name: str, value: str) -> str:
    return (
        f'  <data name="{name}" xml:space="preserve">\n'
        f"    <value>{escape_xml(value)}</value>\n"
        f"  </data>\n"
    )


def add_missing_entries(path: str, translations: dict[str, str]) -> int:
    existing = parse_keys(path)
    to_add = {k: v for k, v in translations.items() if k not in existing}
    if not to_add:
        return 0

    block = "".join(format_entry(name, to_add[name]) for name in sorted(to_add.keys()))

    with open(path, "r", encoding="utf-8-sig") as f:
        content = f.read()

    if "</root>" not in content:
        raise ValueError(f"Invalid resx (no </root>): {path}")

    content = content.replace("</root>", f"{block}</root>", 1)

    with open(path, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(content)

    return len(to_add)


def main() -> int:
    total = 0
    for lang in LANG_FILES:
        wpf_path = os.path.join(REPO, MODULES["WPF"], f"Resource.{lang}.resx")
        wpf_batch: dict[str, str] = {}
        if lang in WPF_TRANSLATIONS:
            wpf_batch.update(WPF_TRANSLATIONS[lang])
        if lang in WPF_LANGUAGE_INSTALL_PROGRESS:
            wpf_batch.update(WPF_LANGUAGE_INSTALL_PROGRESS[lang])
        if wpf_batch:
            n = add_missing_entries(wpf_path, wpf_batch)
            if n:
                print(f"WPF/{lang}: added {n} keys")
                total += n

        lib_path = os.path.join(REPO, MODULES["Lib"], f"Resource.{lang}.resx")
        if lang in LIB_TRANSLATIONS and os.path.exists(lib_path):
            n = add_missing_entries(lib_path, LIB_TRANSLATIONS[lang])
            if n:
                print(f"Lib/{lang}: added {n} keys")
                total += n

    print(f"Done. Total entries added: {total}")
    return 0


